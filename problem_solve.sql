-- 01 - List the productName, productLine, and buyPrice of all products, sorted by price from highest to lowest.--

select productName, productLine, buyPrice from products order by buyPrice desc;

-- 02-Find the names and phone numbers of all customers located in the USA. --

select customerName, phone from customers where country = 'USA';

-- 03 - Display the top 5 products with the lowest quantityInStock --

select * from products order by quantityInStock asc limit 5;

-- 04 - List all unique cities where the company has offices. --

select distinct city from offices where officeCode is not null;

-- 05 : Find the first and last names of all employees who have the job title 'Sales Rep'. --

select firstName , lastName from employees where jobTitle = 'Sales Rep';

-- 06 : Count how many customers are in each country. Sort the results by the count in descending order. --

select country , count(customerNumber) as counter from customers group by country order by counter desc;

-- 07 : Calculate the average buyPrice for each productLine. --

select productLine, avg(buyPrice) as average_buying_price FROM  products group BY productLine ;

-- 08 : List the names of customers who have made individual payments greater than $100,000. --

select c.customerName, sum(p.amount) as total_amount from customers c join payments p on c.customerNumber = p.customerNumber group by c.customerName having total_amount > 100000; 

-- 09 : List every order (orderNumber) along with the total number of items ordered and the total cost for that order. --

select o.orderNumber, sum(od.quantityOrdered) as total_order, SUM(od.priceEach * od.quantityOrdered) as total_price
		from orders o 
		left join orderdetails od on o.orderNumber = od.orderNumber  
		group by o.orderNumber;

-- 10 : Perform a Self-Join on the employees table to show each employee's name alongside their manager's name. --

select concat(e.firstName,' ', e.lastName) as full_name, concat(e1.firstName,' ', e1.lastName) as manager_name 
from employees e 
left join employees e1 on e.employeeNumber = e1.reportsTo ;

-- 11 : Find all products that have never been ordered --

select p.productCode, count(od.orderNumber) from products p left join orderdetails od on p.productCode = od.productCode group by p.productCode having count(od.orderNumber) <= 0;

-- 12 : find the total revenue generated by each office --


SELECT 
    o.city, 
    SUM(p.amount) AS total_revenue from offices o
INNER JOIN employees e ON o.officeCode = e.officeCode
INNER JOIN customers c ON e.employeeNumber = c.salesRepEmployeeNumber
INNER JOIN payments p  ON c.customerNumber = p.customerNumber
GROUP BY o.city
ORDER BY total_revenue DESC;






















